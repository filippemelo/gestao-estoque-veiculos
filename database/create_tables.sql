-- 1. Tabela de Veículos

CREATE TABLE VEICULO (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MARCA           VARCHAR2(50) NOT NULL,
    MODELO          VARCHAR2(100) NOT NULL,
    ANO             NUMBER(4) NOT NULL,
    COR             VARCHAR2(30) NOT NULL,
    PRECO           NUMBER(10,2) NOT NULL,
    TIPO            VARCHAR2(30) NOT NULL,
    SITUACAO        VARCHAR2(20) NOT NULL,
    PLACA           VARCHAR2(10) NOT NULL,
    QUILOMETRAGEM   NUMBER NOT NULL,

    CONSTRAINT PK_VEICULO
        PRIMARY KEY (ID),

    CONSTRAINT UK_VEICULO_PLACA
        UNIQUE (PLACA)
);

ALTER TABLE VEICULO
ADD CONSTRAINT CK_VEICULO_SITUACAO
CHECK (SITUACAO IN ('Disponível', 'Vendido', 'Reservado'));

ALTER TABLE VEICULO
ADD CONSTRAINT CK_VEICULO_PRECO
CHECK (PRECO >= 0);

ALTER TABLE VEICULO
ADD CONSTRAINT CK_VEICULO_QUILOMETRAGEM
CHECK (QUILOMETRAGEM >= 0);

ALTER TABLE VEICULO
ADD CONSTRAINT CK_VEICULO_ANO
CHECK (ANO >= 1900);


-- 2. Tabela de Proprietários

CREATE TABLE PROPRIETARIO (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VEICULO_ID       NUMBER NOT NULL,
    NOME_COMPLETO    VARCHAR2(100) NOT NULL,
    CPF             VARCHAR2(14) NOT NULL,
    DATA_AQUISICAO   DATE NOT NULL,
    DATA_VENDA       DATE NULL,
    OBSERVACAO      VARCHAR2(255),

    CONSTRAINT PK_PROPRIETARIO
        PRIMARY KEY (ID),

    CONSTRAINT FK_PROPRIETARIO_VEICULO
        FOREIGN KEY (VEICULO_ID)
        REFERENCES VEICULO (ID)
);

ALTER TABLE PROPRIETARIO
ADD CONSTRAINT CK_PROPRIETARIO_DATAS
CHECK (DATA_VENDA IS NULL OR DATA_VENDA >= DATA_AQUISICAO);
